# Build WordCraft for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-wordcraft-web.sh [WORDCRAFT_CHECKOUT]
#
#   WORDCRAFT_CHECKOUT  an existing clone of github.com/storytold/wordcraft. Without it the
#                       script clones WORDCRAFT_REF into build/wordcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in WordCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   WORDCRAFT_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORDCRAFT_REF="${WORDCRAFT_REF:-81bf9187f2704afda65774734f3a22d8e94a4e2c}"
SRC="${1:-$APP_DIR/build/wordcraft}"
PATCH="$APP_DIR/patches/wordcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/wordcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$WORDCRAFT_REF"
fi

if grep -q 'wordcraft:ready' "$SRC/apps/wordcraft-web/src/web.rs"; then
	echo "bridge patch already applied"
else
	git -C "$SRC" apply "$PATCH"
fi

cargo_args=(build --release -p wordcraft-web --target wasm32-unknown-unknown)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/wordcraft-web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
# --weak-refs as WordCraft's own build (Trunk's data-weak-refs).
wasm-bindgen --target web --weak-refs --no-typescript --out-dir "$STAGE" --out-name wordcraft-web "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/wordcraft-web_bg.wasm" -o "$STAGE/wordcraft-web_bg.opt.wasm"
	mv "$STAGE/wordcraft-web_bg.opt.wasm" "$STAGE/wordcraft-web_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

# Content-hashed names: Nextcloud lets browsers cache app assets for months.
hash() { sha256sum "$1" | cut -c1-16; }
JS_NAME="wordcraft-web-$(hash "$STAGE/wordcraft-web.js").js"
WASM_NAME="wordcraft-web-$(hash "$STAGE/wordcraft-web_bg.wasm").wasm"

mkdir -p "$OUT"
rm -f "$OUT"/wordcraft-web-*.js "$OUT"/wordcraft-web-*.wasm
cp "$STAGE/wordcraft-web.js" "$OUT/$JS_NAME"
cp "$STAGE/wordcraft-web_bg.wasm" "$OUT/$WASM_NAME"

# WordCraft's licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/WORDCRAFT-$f"; fi
done

cat > "$OUT/boot.js" <<EOF
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts WordCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-wordcraft-web.sh from WordCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('WordCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'wordcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	const { default: init } = await import('./$JS_NAME')
	await init({ module_or_path: new URL('./$WASM_NAME', import.meta.url) })
} catch (error) {
	reportFailure(error)
}
EOF

echo "WordCraft web build:"
ls -lh "$OUT"
